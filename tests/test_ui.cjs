// All demonstration counters and identities are invented, never copied from a real session.
const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,...(process.env.UI_TEST_BROWSER ? {executablePath:process.env.UI_TEST_BROWSER} : {})});
  try {
    const context = await browser.newContext({viewport:{width:900,height:700}});
    await context.route(/^https?:/, route=>route.abort());
    const page = await context.newPage();
    const errors=[];
    page.on('pageerror', error=>errors.push(String(error)));
    await page.addInitScript(() => {
      window.commands=[]; window.answers=[];
      window.mockState={status:{text:'Disconnected'},message:{text:'Your normal internet is unchanged.'},power_button:{text:'⏻  Check phone',state:'normal',style:'Power.TButton'},maintenance:{can_prepare:true,can_send:false,can_copy:false,can_retire:false}};
      window.pywebview={api:{get_state:async()=>window.mockState, command:async name=>{window.commands.push(name);return true;},answer_dialog:async(id,value)=>{window.answers.push([id,value]);window.mockState.dialog=null;return true;},move_window:async()=>true,minimize:async()=>true}};
    });
    await page.goto(pathToFileURL(path.resolve(__dirname,'../src/ui/index.html')).href);
    await page.evaluate(()=>window.dispatchEvent(new Event('pywebviewready')));
    await page.waitForFunction(()=>!document.querySelector('#power').disabled);
    const toggle=async(id,open)=>{
      if(await page.locator('#'+id).evaluate(el=>el.open)!==open) await page.locator('#'+id+' > summary').click();
      assert.equal(await page.locator('#'+id).evaluate(el=>el.open),open);
    };
    const screenshot=async name=>{
      await page.mouse.move(480,10);
      await page.waitForTimeout(200);
      await page.screenshot({path:path.join(__dirname,'../build/ui-tests/'+name+'.png')});
    };
    fs.mkdirSync(path.join(__dirname,'../build/ui-tests'),{recursive:true});
    assert.equal(await page.title(),'iPhone USB Internet');
    assert.equal(await page.locator('.brand-name').innerText(),'iPhone USB Internet');
    assert.equal(await page.locator('.brand-credit').innerText(),'Made by Zuyis');
    assert.equal(await page.locator('aside,nav,.rail,[data-page],[id^="page-"],#pageSearch,#search-results,.tool-search').count(),0);
    assert.equal(await page.locator('progress,[role=progressbar],footer,#help,#details,#maintenance,#error-panel,#error-text').count(),0);
    assert.equal(await page.locator('.setup-card ol > li').count(),3);
    assert.equal(await page.locator('details[open]').count(),0);
    assert.equal(await page.locator('.dashboard > .section-card > .section-head .section-icon').count(),4);
    assert.equal(await page.locator('.dashboard > .section-card > .section-head .section-title').count(),4);
    assert.equal(await page.locator('.dashboard > .section-card > .section-head .section-description').count(),4);
    const ids=await page.locator('[id]').evaluateAll(elements=>elements.map(el=>el.id));
    assert.equal(new Set(ids).size,ids.length,'No duplicate IDs after merging pages');
    assert.deepEqual(await page.evaluate(()=>window.commands),[]);
    for(const forbidden of ['Dark dashboard','17 Oct','YOUR CONNECTION','Phone internet, one cable.','Recheck phone','Full error message']) assert(!(await page.locator('body').innerText()).includes(forbidden));
    const style=await page.locator('.hero').evaluate(el=>({radius:getComputedStyle(el).borderRadius,font:getComputedStyle(el).fontFamily}));
    assert.equal(style.radius,'14px'); assert(style.font.includes('Segoe UI Variable Text'));
    await page.locator('#diagnostics > summary').focus();
    await page.keyboard.press('Enter');
    assert(await page.locator('#failed-value').isVisible());
    await page.keyboard.press('Space');
    assert(!(await page.locator('#failed-value').isVisible()));
    await page.locator('[data-expand=setup]').click();
    assert(await page.locator('#setup-tools').evaluate(el=>el.open));
    assert.equal(await page.evaluate(()=>document.activeElement.parentElement.id),'setup-tools');
    await toggle('old-keys',true);
    assert(await page.locator('#retire_keys').isDisabled());
    await toggle('old-keys',false);
    await toggle('setup-tools',false);
    await toggle('about-panel',true);
    assert((await page.locator('#about-panel').innerText()).includes('Educational Purposes Only'));
    assert((await page.locator('#about-panel').innerText()).includes('have not been verified'));
    await toggle('license-details',true);
    assert((await page.locator('#license-text').innerText()).includes('PolyForm Noncommercial'));
    await toggle('license-details',false);
    await toggle('about-panel',false);
    assert.deepEqual(await page.evaluate(()=>window.commands),[]);
    await page.locator('#power').click();
    assert.deepEqual(await page.evaluate(()=>window.commands),['power']);
    await page.evaluate(()=>{window.mockState.power_button={text:'⏻  Connect PC',state:'normal',style:'Power.TButton'};window.mockState.status={text:'Phone ready'};});
    await page.waitForFunction(()=>document.querySelector('#power-text').textContent==='Connect PC');
    assert.deepEqual(await page.evaluate(()=>window.commands),['power'],'Phone-ready must not auto-connect');
    await page.evaluate(()=>{window.mockState.dialog={id:'fixture',title:'Fixture confirmation',message:'<img src=x onerror=alert(1)>',confirm:true};});
    await page.waitForFunction(()=>document.querySelector('#dialog').open);
    assert.equal(await page.locator('#dialog-message img').count(),0);
    assert.equal(await page.evaluate(()=>document.activeElement.id),'cancel');
    await page.keyboard.press('Escape');
    await page.waitForFunction(()=>!document.querySelector('#dialog').open);
    assert.deepEqual(await page.evaluate(()=>window.answers),[['fixture',false]]);
    await page.evaluate(()=>{
      Object.assign(window.mockState,{connection_state:'connected',status:{text:'Connected',fg:'#65d68e'},message:{text:'Phone route is active. Keep iSH visible and your iPhone unlocked.'},download:{text:'12.0 MB'},upload:{text:'3.0 MB'},sessions:{text:'4 / 384'},diagnostics:{fresh:true,recorded:true,active:4,capacity:384,waiting:0,rejected:0,failures:1,peak_active:8,peak_waiting:1,dns_parked:20,usb:{condition:'good',age:2,latency:20},internet:{condition:'good',age:9}},power_button:{text:'⏻  Disconnect',state:'normal',style:'Stop.TButton'},health_label:{text:'USB: responding (2s ago) / 20 ms USB response | HTTPS: last passed 9s ago\nCapacity: available\nPeaks: 8 active / 1 waiting.'}});
      document.querySelector('main').scrollTop=0;
    });
    await page.waitForFunction(()=>document.querySelector('#power').classList.contains('connected'));
    assert.equal(await page.locator('#usb-state').innerText(),'Responding');
    assert.equal(await page.locator('#capacity-state').innerText(),'Available');
    await screenshot('connection');
    const frame=await page.evaluate(()=>{
      const main=document.querySelector('main').getBoundingClientRect();
      const hero=document.querySelector('.hero').getBoundingClientRect();
      const bar=document.querySelector('.titlebar').getBoundingClientRect();
      return {content:[hero.left,innerWidth-hero.right,hero.top-bar.bottom],viewport:[main.left,innerWidth-main.right,main.top-bar.bottom,innerHeight-main.bottom]};
    });
    assert.deepEqual(frame.content,[16,16,16],'Content has equal initial insets');
    assert.deepEqual(frame.viewport,[0,0,0,0],'Scrollbar reaches the right edge; scroll viewport meets titlebar and window bottom');
    assert(await page.locator('#copy').evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight-16),'Daily phone command fits in the shorter window');
    await page.evaluate(()=>{document.querySelector('main').scrollTop=100;});
    const scrollEdges=await page.evaluate(()=>{
      const top=document.querySelector('.titlebar').getBoundingClientRect().bottom+1;
      return [document.querySelector('.hero').contains(document.elementFromPoint(40,top)),
              document.querySelector('#about-panel').contains(document.elementFromPoint(40,innerHeight-1))];
    });
    assert.deepEqual(scrollEdges,[true,true],'Cards scroll under the titlebar and through the bottom edge without fixed blank bands');
    await screenshot('connection-scrolled');
    await page.evaluate(()=>{const main=document.querySelector('main');main.scrollTop=main.scrollHeight;});
    assert(await page.locator('#about-panel > summary').isVisible());
    await screenshot('connection-bottom');
    const endInsets=await page.locator('#about-panel').evaluate(el=>{const r=el.getBoundingClientRect();return [r.left,innerWidth-r.right,innerHeight-r.bottom];});
    assert(endInsets.every(value=>Math.abs(value-16)<.5),'Bottom spacing appears at the end of the content, matching side insets');
    await toggle('diagnostics',true);
    assert.equal(await page.locator('#failed-value').innerText(),'1');
    await page.locator('#diagnostics').evaluate(el=>el.scrollIntoView({block:'start'}));
    await screenshot('diagnostics');
    await page.evaluate(()=>{window.mockState.diagnostics.fresh=false;});
    await page.waitForFunction(()=>document.querySelector('#diagnostic-live').textContent==='Delayed');
    assert.equal(await page.locator('#usb-state').innerText(),'Unknown');
    await toggle('diagnostics',false);
    await page.evaluate(()=>{Object.assign(window.mockState,{connection_state:'error',message:{text:'Connect your paired iPhone by USB, unlock it, and tap Trust if asked.'},status:{text:'Not connected'},power_button:{text:'⏻  Check phone',state:'normal',style:'Power.TButton'}});});
    await page.waitForFunction(()=>document.querySelector('#message').textContent.startsWith('Connect your paired'));
    assert.equal(await page.getByText('Connect your paired iPhone by USB, unlock it, and tap Trust if asked.',{exact:true}).count(),1);
    await page.evaluate(()=>{window.mockState.message={text:'Phone check did not pass: Connect exactly one iPhone by USB, unlock it, and tap Trust. If already paired here, reconnect that same iPhone.\nKeep the paired phone unlocked with iSH running. PC internet is unchanged.'};});
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('exactly one'));
    for(const viewport of [{width:1000,height:760},{width:900,height:660},{width:780,height:620}]) {
      await page.setViewportSize(viewport);
      await page.locator('#power').scrollIntoViewIfNeeded();
      assert(await page.locator('#power').isVisible());
      assert(await page.evaluate(()=>document.querySelector('main').scrollWidth<=document.querySelector('main').clientWidth));
      assert(await page.locator('.hero').evaluate(el=>el.scrollHeight<=el.clientHeight+1),'Long error must not crop metrics');
      assert(await page.locator('.brand').evaluate(el=>el.getBoundingClientRect().right<document.querySelector('.window-buttons').getBoundingClientRect().left),'Credit must not overlap window controls');
      await page.locator('#copy').scrollIntoViewIfNeeded();
      assert(await page.locator('#copy').isVisible());
    }
    await toggle('setup-tools',true);
    await page.locator('#prepare_update').click();
    assert.deepEqual(await page.evaluate(()=>window.commands),['power','prepare_update']);
    await page.evaluate(()=>Object.assign(window.mockState.maintenance,{receiver:'fixture receiver command',can_send:true,can_copy:true,update_result:'Ready fixture'}));
    await page.waitForFunction(()=>!document.querySelector('#receiver-card').hidden);
    assert.equal(await page.locator('#receiver-command').inputValue(),'fixture receiver command');
    await toggle('setup-tools',false);
    await toggle('setup-tools',true);
    assert.equal(await page.locator('#receiver-command').inputValue(),'fixture receiver command','Collapsing setup preserves its result');
    assert(!(await page.locator('#dialog').isVisible()));
    await page.evaluate(()=>{window.savedGetState=window.pywebview.api.get_state;window.pywebview.api.get_state=async()=>{throw Error('Fixture renderer bridge loss');};});
    await page.waitForFunction(()=>document.querySelector('#health_label').textContent.includes('App status is unavailable'));
    for(const id of ['power','prepare_update','send_update','copy_receiver','retire_keys']) assert(await page.locator('#'+id).isDisabled());
    await page.evaluate(()=>{window.pywebview.api.get_state=window.savedGetState;});
    await page.waitForFunction(()=>!document.querySelector('#prepare_update').disabled);
    await page.evaluate(()=>{window.pywebview.api.command=async()=>{throw Error('Fixture command failure');};});
    await page.locator('#prepare_update').click();
    await page.waitForTimeout(200);
    assert.deepEqual(errors,[],'Bridge failures must not leave unhandled promise rejections');
    await toggle('setup-tools',false);
    await page.setViewportSize({width:900,height:700});
    await page.evaluate(()=>{window.mockState.app={paired:false,can_pair:true,version:'1.2.0'};window.mockState.connection_state='stopped';window.mockState.power_button={text:'Check phone',state:'normal'};window.commands=[];window.pywebview.api.command=async name=>{window.commands.push(name);return true;};});
    await page.waitForFunction(()=>document.querySelector('#power-text').textContent==='Set up phone');
    await page.locator('#power').click();
    assert(await page.locator('#setup-tools').evaluate(el=>el.open));
    assert.deepEqual(await page.evaluate(()=>window.commands),[],'Unpaired primary action opens setup without connecting');
    assert(await page.locator('#prepare_update').isDisabled());
    await page.locator('#pair_phone').click();
    assert.deepEqual(await page.evaluate(()=>window.commands),['pair_phone']);
    await page.evaluate(()=>Object.assign(window.mockState.app,{paired:true,can_pair:false}));
    await page.waitForFunction(()=>document.querySelector('#pair_phone').hidden);
    await page.locator('#setup-tools').evaluate(el=>el.scrollIntoView({block:'start'}));
    await screenshot('setup-single-page');
    await toggle('setup-tools',false);
    await toggle('about-panel',true);
    await page.locator('#about-panel').evaluate(el=>el.scrollIntoView({block:'start'}));
    await screenshot('about-single-page');
    assert.deepEqual(errors,[]);
    console.log('PASS: single-page layout; header credit; keyboard disclosures; no sidebar/search/updater; paired/unpaired flows; health states; single error; three window sizes; receiver persistence; dialog escaping; bridge recovery. All backend actions mocked, external requests blocked.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
